#!/usr/bin/env node
/**
 * Build the PyTorch live-helper adversarial fixture plate.
 *
 * Csmith/CompCert discipline: bad fixtures are NEVER captured from a live
 * broken helper — that would make them byte-unstable across helper
 * versions and platform-non-deterministic. This script:
 *
 *   1. READS the three GOOD helper-emitted golden sidecars that
 *      scripts/generate-pytorch-helper-goldens.py produced from REAL
 *      PyTorch (bias=True, per-neuron biases — the live helper's true
 *      emission shape). These are checked into fixtures/external/ so this
 *      Node script needs NO torch (G-035 / G-017).
 *
 *   2. Derives the bad-helper fixtures by applying targeted byte-level
 *      mutations to those goldens. Each mutation simulates a documented
 *      PyTorch-extraction failure mode (see docs/live-helpers.md
 *      "Adversarial fixture catalog").
 *
 *   3. Writes the matching .meta.json files documenting what was mutated
 *      and which reconciler rule must fire when bp reconcile reads the
 *      sidecar through bp import pytorch.
 *
 * Reproducibility: CI re-runs THIS script (Node-only) and
 * `git diff --exit-code` confirms byte-identical regeneration of the bad
 * plate — the input goldens are fixed checked-in bytes and every mutation
 * is deterministic. The goldens themselves are regenerated by the
 * torch-gated generator (and torch-gated test) only where torch exists.
 *
 * HISTORY (G-035): the goldens were previously DERIVED here from
 * hand-authored per_layer sidecars (w_x ids, shared b_hidden / b_output,
 * constant biases), so the helper's REAL per-neuron emission contract was
 * never exercised by the fixtures. They now come straight from the live helper.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = resolve(HERE, "..")
const FIXTURES_EXT = resolve(REPO_ROOT, "fixtures", "external")
const FIXTURES_BAD = resolve(REPO_ROOT, "fixtures", "bad")

function readJSONLLine(path) {
  const text = readFileSync(path, "utf-8")
  const lines = text.split("\n").filter((l) => l.length > 0)
  if (lines.length !== 1) {
    throw new Error(`expected exactly 1 line in ${path}; got ${lines.length}`)
  }
  return JSON.parse(lines[0])
}

function writeMetaJSON(path, meta) {
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, JSON.stringify(meta, null, 2) + "\n", "utf-8")
}

function writeJSONLLine(path, obj) {
  mkdirSync(dirname(path), { recursive: true })
  const text = JSON.stringify(obj) + "\n"
  writeFileSync(path, text, "utf-8")
}

